def load_calendar(file_path, experiment):
    """
    Read calendar events from an ICS file.

    calendar-bench writes two kinds of events into one .ics file:
    planned tasks (breakfast, meeting, sleep, ...) and context annotations
    ('[ctx:location] home', '[ctx:energy_state] tired', ...). They are
    returned separately: (tasks, context_events). Each task is matched to
    the event catalog and persona of the experiment.
    """
    if not file_path.exists():
        raise FileNotFoundError(
            f"Calendar file not found:\n{file_path}\n\n"
            "Check that the filename and folder are correct."
        )

    with file_path.open("rb") as file:
        calendar = Calendar.from_ical(file.read())

    tasks = []
    context_events = []

    for index, event in enumerate(calendar.walk("VEVENT")):
        start_raw = event.get("DTSTART")
        if start_raw is None:
            continue

        start = normalize_datetime(start_raw.dt)

        end_raw = event.get("DTEND")
        duration_raw = event.get("DURATION")

        if end_raw is not None:
            end = normalize_datetime(end_raw.dt)
            duration_hours = max(
                0, (end - start).total_seconds() / 3600
            )
        elif duration_raw is not None:
            duration_hours = max(
                0, duration_raw.dt.total_seconds() / 3600
            )
            end = start + timedelta(hours=duration_hours)
        else:
            end = None
            duration_hours = None

        summary = str(event.get("SUMMARY", "Untitled event"))
        record = {
            # calendar-bench files have no UID: use a synthetic one
            "uid": str(event.get("UID", "")) or f"evt-{index:05d}",
            "summary": summary,
            "description": str(event.get("DESCRIPTION", "")),
            "start": start,
            "end": end,
            "duration_hours": duration_hours,
            "status": str(event.get("STATUS", "")),
            "all_day": isinstance(start_raw.dt, date)
                        and not isinstance(start_raw.dt, datetime),
        }

        context = parse_context_event(summary, categories_text(event))
        if context is not None:
            record["context_category"], record["context_value"] = context
            context_events.append(record)
        else:
            tasks.append(enrich_task(record, experiment))

    tasks.sort(key=lambda task: task["start"])
    context_events.sort(key=lambda item: item["start"])
    return tasks, context_events


