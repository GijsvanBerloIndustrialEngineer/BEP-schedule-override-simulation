def normalize_datetime(value):
    """Convert an ICS date or datetime into a Python datetime."""
    if isinstance(value, datetime):
        # Convert timezone-aware values to the computer's local time,
        # then remove timezone information for consistent calculations.
        if value.tzinfo is not None:
            value = value.astimezone().replace(tzinfo=None)
        return value

    if isinstance(value, date):
        return datetime.combine(value, datetime.min.time())

    return None


def categories_text(event):
    """CATEGORIES of an ICS event as plain text ('' if absent)."""
    raw = event.get("CATEGORIES")
    if raw is None:
        return ""
    items = raw if isinstance(raw, list) else [raw]
    names = []
    for item in items:
        cats = getattr(item, "cats", None)
        if cats:
            names.extend(str(c) for c in cats)
        else:
            names.append(str(item))
    return ",".join(names)


